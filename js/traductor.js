function cambiarIdioma(idioma) {
    document.querySelectorAll('[data-i18n]').forEach(elemento => {
        const clave = elemento.getAttribute('data-i18n');
        if (traducciones[idioma] && traducciones[idioma][clave]) {
            if (elemento.tagName.toLowerCase() === 'input' && (elemento.type === 'submit' || elemento.type === 'reset')) {
                elemento.value = traducciones[idioma][clave];
            } else if (elemento.tagName.toLowerCase() === 'input' || elemento.tagName.toLowerCase() === 'textarea') {
                elemento.placeholder = traducciones[idioma][clave];
            } else {
                elemento.innerHTML = traducciones[idioma][clave];
            }
        }
    });
    localStorage.setItem('idiomaCiberShield', idioma);
    const selector = document.getElementById('selector-idioma');
    if (selector) selector.value = idioma;
}

document.addEventListener('DOMContentLoaded', () => {
    cambiarIdioma(localStorage.getItem('idiomaCiberShield') || 'es');
});